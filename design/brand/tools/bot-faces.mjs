// Writes the swappable bot-face assets from bot-identity/faces.js:
//   bot-identity/faces/<id>.svg   one file per face; colours from --bot-face, --bot-ink, --bot-rim
//   bot-identity/faces/manifest.json   the preset ids (config avatar.preset), names and expressions,
//                                      plus the identity palette (light and dark) from tokens.json
// Run after changing a face: node tools/bot-faces.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.join(here, '..', 'bot-identity');
const { FACES, faceSVG } = await import(pathToFileURL(path.join(dir, 'faces.js')).href);
const T = JSON.parse(fs.readFileSync(path.join(here, '..', 'tokens', 'tokens.json'), 'utf8'));
fs.mkdirSync(path.join(dir, 'faces'), { recursive: true });
for (const [id] of FACES) fs.writeFileSync(path.join(dir, 'faces', `${id}.svg`), faceSVG(id, { asFile: true, size: 96 }) + '\n');
const bot = T.semantic.color.bot;
const palette = Object.keys(bot).filter((k) => !k.startsWith('$')).map((k) => ({
  id: k, token: `--color-bot-${k}-bg`, ink: `--color-bot-${k}-fg`,
  light: { fill: bot[k].bg.$extensions.mode.light.hex, ink: bot[k].fg.$extensions.mode.light.hex },
  dark: { fill: bot[k].bg.$extensions.mode.dark.hex, ink: bot[k].fg.$extensions.mode.dark.hex },
}));
const manifest = {
  $comment: 'Bot faces for conductor (Daylight). The ids are avatar.preset values: stable, never renamed. Files take --bot-face (fill), --bot-ink (features) and --bot-rim (optional edge on dark pages). Generated by tools/bot-faces.mjs.',
  faces: FACES.map(([id, name, expression]) => ({ id, name, expression, file: `${id}.svg` })),
  palette,
};
fs.writeFileSync(path.join(dir, 'faces', 'manifest.json'), JSON.stringify(manifest, null, 1) + '\n');
console.log(`${FACES.length} faces, ${palette.length} colours → bot-identity/faces/`);
