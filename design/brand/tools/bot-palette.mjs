// The bot accent palette (chosen: option A, which keeps clear of every status hue). Derives each colour from an OKLCH spec, writes
// the results into tokens/tokens.json (semantic.color.bot.*), and reports the checks in
// bot-identity/PALETTE.md:
//   - the face (drawn in ink) and initials on the fill are AA in both themes (≥ 4.5:1);
//   - every colour's hue is at least 20° from every status hue (danger, needs-you ember, waiting,
//     passed, running, parked, shadow), so a bot's colour never reads as a state;
//   - fills are pastel in light and deep in dark: a different lightness and chroma from the status
//     solids (OKLab ΔE×100 to the nearest status solid is reported);
//   - how far apart the bot colours are from one another, for colour-blind and normal vision.
//
//   DATAVIZ_VALIDATOR=/path/to/validate_palette.js node tools/bot-palette.mjs
// Then run node tools/tokens.mjs to regenerate tokens.css and the contrast gate.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { oklch, toHex, contrast } from './oklch.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const tokPath = path.join(here, '..', 'tokens', 'tokens.json');
const T = JSON.parse(fs.readFileSync(tokPath, 'utf8'));
const { validate } = await import(pathToFileURL(process.env.DATAVIZ_VALIDATOR).href);

// name, hue, [light L, C], [dark L, C]. Hues sit in the bands the status colours leave free
// (100–132, 172–212, 312–352). Lightness was searched (light 0.72–0.88, dark 0.36–0.52, so every
// avatar stands off its surface) to keep the colours as far apart as those bands allow.
// Stone is the one chromatic neutral; Ink is the inverse (ink fill, cream picture).
export const SPEC = [
  ['olive', 102, [0.72, 0.085], [0.52, 0.077]], ['lime', 124, [0.88, 0.08], [0.44, 0.072]],
  ['teal', 182, [0.72, 0.075], [0.40, 0.068]], ['lagoon', 206, [0.88, 0.06], [0.47, 0.078]],
  ['plum', 316, [0.72, 0.085], [0.40, 0.077]], ['rose', 348, [0.88, 0.08], [0.48, 0.072]],
  ['stone', 70, [0.80, 0.014], [0.36, 0.013]],
];
const get = (p) => p.split('.').reduce((o, k) => o[k], T);
const hexOf = (p, th) => { let t = get(p), v = t.$extensions?.mode?.[th] ?? t.$value; while (typeof v === 'string') { t = get(v.slice(1, -1)); v = t.$extensions?.mode?.[th] ?? t.$value; } return v.hex; };
const comps = (h) => [1, 3, 5].map((i) => +(parseInt(h.slice(i, i + 2), 16) / 255).toFixed(4));
const colour = (h) => ({ colorSpace: 'srgb', components: comps(h), hex: h });
const STATUS = { danger: 'semantic.color.status.danger.solid', 'needs you': 'semantic.color.accent.default', waiting: 'semantic.color.status.warning.solid', passed: 'semantic.color.status.success.solid', running: 'semantic.color.status.running.solid', parked: 'semantic.color.status.neutral.solid', shadow: 'semantic.color.status.info.solid' };
const lab = (h) => { const [L, C, H] = oklch(h); return [L, C * Math.cos((H * Math.PI) / 180), C * Math.sin((H * Math.PI) / 180)]; };
const dE = (a, b) => { const [x, y] = [lab(a), lab(b)]; return 100 * Math.hypot(x[0] - y[0], x[1] - y[1], x[2] - y[2]); };
const hueGap = (a, b) => { const d = Math.abs(a - b) % 360; return Math.min(d, 360 - d); };

const out = {};
for (const th of ['light', 'dark']) {
    out[th] = SPEC.map(([name, h, lc, dc]) => {
    // The face is drawn in the theme's ink (text.primary: dark ink in light, cream in dark), so fills
    // are pastel in light and deep in dark, where the status colours are the light ones.
    const [l, c] = th === 'light' ? lc : dc; const bg = toHex(l, c, h), fg = hexOf('semantic.color.text.primary', th);
    return { name, hue: h, bg, fg };
  });
}

// Write the tokens: semantic.color.bot.<name>.bg / .fg, light and dark, with a 4.5:1 contrast intent.
const bot = { $description: 'Bot identity colours: the fill behind a bot’s face or initials (drawn in ink), and a 3px rule on its chat messages. Never on status marks, buttons, links, counts, row edges, charts or text. Every hue keeps 20° clear of the status colours. Generated by tools/bot-palette.mjs.' };
SPEC.forEach(([name], i) => {
  const L = out.light[i], D = out.dark[i];
  bot[name] = {
    bg: { $type: 'color', $value: colour(D.bg), $extensions: { mode: { dark: colour(D.bg), light: colour(L.bg) } }, $description: `Avatar fill: ${name}.` },
    rule: { $type: 'color', $value: colour(L.bg), $extensions: { mode: { dark: colour(L.bg), light: colour(D.bg) }, 'org.conductor.contrast': { on: ['semantic.color.bg.surface', 'semantic.color.bg.canvas', 'semantic.color.bg.raised'], min: 3 } }, $description: `The 3px rule on the bot’s own chat messages (${name}): the other theme’s fill (deep in light, pastel in dark), so it shows at 3:1 on either page.` },
    fg: { $type: 'color', $value: colour(D.fg), $extensions: { mode: { dark: colour(D.fg), light: colour(L.fg) }, 'org.conductor.contrast': { on: [`semantic.color.bot.${name}.bg`], min: 4.5 } }, $description: `The face and initials on the ${name} fill: the theme’s ink.` },
  };
});
T.semantic.color.bot = bot;
fs.writeFileSync(tokPath, JSON.stringify(T, null, 2) + '\n');

// Report.
const md = ['# Bot accent palette: checks', '', 'GENERATED by `tools/bot-palette.mjs`. Fills are pastel in light and deep in dark; the face and initials are drawn on top in the theme’s ink (dark ink in light, cream in dark).', ''];
let bad = 0;
for (const th of ['light', 'dark']) {
  const status = Object.fromEntries(Object.entries(STATUS).map(([k, p]) => [k, hexOf(p, th)]));
  md.push(`## ${th}`, '', '| Colour | Fill | Picture | Picture on fill | Nearest status hue | Hue gap | ΔE to nearest status solid |', '|---|---|---|---|---|---|---|');
  for (const c of out[th]) {
    const con = contrast(c.fg, c.bg);
    let gap = '—', near = '—';
    if (c.hue != null && c.name !== 'stone') { const g = Object.entries(status).filter(([k]) => k !== 'parked').map(([k, h]) => [k, hueGap(c.hue, oklch(h)[2])]).sort((a, b) => a[1] - b[1])[0]; near = g[0]; gap = `${g[1].toFixed(0)}°`; if (g[1] < 20) bad++; }
    const nearDE = Math.min(...Object.values(status).map((h) => dE(c.bg, h)));
    if (con < 4.5) bad++;
    md.push(`| ${c.name} | \`${c.bg}\` | \`${c.fg}\` | ${con.toFixed(2)}${con < 4.5 ? ' **below 4.5**' : ''} | ${near} | ${gap} | ${nearDE.toFixed(1)} |`);
  }
  const fills = out[th].map((c) => c.bg);
  let minPair = [99, '', ''];
  for (let i = 0; i < fills.length; i++) for (let j = i + 1; j < fills.length; j++) { const d = dE(fills[i], fills[j]); if (d < minPair[0]) minPair = [d, out[th][i].name, out[th][j].name]; }
  md.push('', `Closest pair to normal vision: ${minPair[1]} and ${minPair[2]}, ΔE ${minPair[0].toFixed(1)}.`);
  console.log(th, 'closest pair', minPair[1], minPair[2], minPair[0].toFixed(1));
  const { report } = validate(fills, { mode: th, surface: hexOf('semantic.color.bg.surface', th), pairs: 'all' });
  const cvd = report.find((r) => r[0] === 'CVD separation'), nor = report.find((r) => r[0] === 'Normal-vision floor');
  md.push('', `Between the bot colours (all pairs, ${th}): ${cvd ? cvd[2] : ''}; normal vision: ${nor ? nor[2] : ''}. A bot is told apart by its picture and name first; its colour is the third signal.`, '');
}
md.push(bad ? `**${bad} problems.**` : 'Every picture is at least 4.5:1 on its fill in both themes, and every chromatic colour is at least 20° of hue from every status colour.', '');
fs.mkdirSync(path.join(here, '..', 'bot-identity'), { recursive: true });
fs.writeFileSync(path.join(here, '..', 'bot-identity', 'PALETTE.md'), md.join('\n'));
fs.writeFileSync(path.join(here, '..', 'bot-identity', 'palette.json'), JSON.stringify(out, null, 1) + '\n');
console.log(bad ? `${bad} problems` : 'bot palette: AA in both themes, ≥ 20° from every status hue');
process.exit(bad ? 1 : 0);
