// Colour-blind check for the scannable proposal's risk markers (scannable/scan.js). The top three
// steps are solid bands: production (inverse ink), money (amber) and destructive (red). Checks, per
// theme, with the dataviz skill's validator (Machado 2009 protan/deutan, OKLab ΔE×100):
//   - every pair of bands is distinct to colour-blind and to normal vision;
//   - each band is ≥ 3:1 against the surface (a non-text mark) and its words are ≥ 4.5:1 on the band;
// and records that every step also differs by shape (the meter's fill) and by its word, so no step
// relies on colour alone. The bottom three steps are ink (tertiary, secondary, primary + bold).
//
//   DATAVIZ_VALIDATOR=/path/to/validate_palette.js node tools/risk-cvd.mjs
// Writes scannable/RISK-CVD.md. Exits 1 on any failure.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const T = JSON.parse(fs.readFileSync(path.join(here, '..', 'tokens', 'tokens.json'), 'utf8'));
const { validate, contrast } = await import(pathToFileURL(process.env.DATAVIZ_VALIDATOR).href);
const get = (p) => p.split('.').reduce((o, k) => o[k], T);
function hex(p, theme) {
  let t = get(p), v = t.$extensions?.mode?.[theme] ?? t.$value;
  while (typeof v === 'string') { t = get(v.slice(1, -1)); v = t.$extensions?.mode?.[theme] ?? t.$value; }
  return v.hex;
}
const pal = (r, s) => `primitive.color.${r}.${s}`;
// Mirrors SCAN_CSS in scannable/scan.js.
const BANDS = {
  light: { 'Changes production': ['semantic.color.bg.inverse', 'semantic.color.text.inverse'], 'Spends money': [pal('amber', 500), pal('sand', 975)], Destructive: [pal('red', 700), pal('sand', 50)] },
  dark: { 'Changes production': ['semantic.color.bg.inverse', 'semantic.color.text.inverse'], 'Spends money': [pal('amber', 300), pal('sand', 975)], Destructive: [pal('red', 400), pal('sand', 975)] },
};
const INK = { 'Reads only': 'semantic.color.text.tertiary', Reversible: 'semantic.color.text.secondary', 'Changes things': 'semantic.color.text.primary' };
const num = (row) => +(row[2].match(/ΔE ([\d.]+)/)?.[1] ?? 0);
let bad = 0;
const out = ['# Risk markers: colour-blind check', '', 'GENERATED by `tools/risk-cvd.mjs` with the dataviz skill’s `validate_palette.js` (Machado 2009 protanopia/deuteranopia, OKLab ΔE×100), on `bg.surface`. The thresholds are a CVD ΔE target of 8 (floor 6) and a normal-vision floor of 15.', '',
  'Colour is the third signal, not the first: every step also has its own **meter fill** (1 to 6 bars) and its own **word**, and the top three are solid bands in bold. So the ladder reads in one colour, in forced-colours mode and in print.', ''];
for (const theme of ['light', 'dark']) {
  const surface = hex('semantic.color.bg.surface', theme);
  out.push(`## ${theme} (surface ${surface})`, '', '| Step | Band | Words on band | Band vs surface | Words vs band |', '|---|---|---|---|---|');
  for (const [name, p] of Object.entries(INK)) out.push(`| ${name} | ink \`${hex(p, theme)}\` (no band) | — | ${contrast(hex(p, theme), surface).toFixed(2)} | — |`);
  const names = Object.keys(BANDS[theme]), bg = names.map((n) => hex(BANDS[theme][n][0], theme));
  names.forEach((n, i) => {
    const fg = hex(BANDS[theme][n][1], theme), cs = contrast(bg[i], surface), cf = contrast(fg, bg[i]);
    if (cs < 3 || cf < 4.5) bad++;
    out.push(`| ${n} | \`${bg[i]}\` | \`${fg}\` | ${cs.toFixed(2)}${cs < 3 ? ' **below 3**' : ''} | ${cf.toFixed(2)}${cf < 4.5 ? ' **below 4.5**' : ''} |`);
  });
  out.push('', '| Pair | CVD ΔE (worst) | Normal ΔE | By colour | Also differs by |', '|---|---|---|---|---|');
  for (let i = 0; i < names.length; i++) for (let j = i + 1; j < names.length; j++) {
    const { report } = validate([bg[i], bg[j]], { mode: theme, surface });
    const cvd = num(report.find((r) => r[0] === 'CVD separation')), nor = num(report.find((r) => r[0] === 'Normal-vision floor'));
    const ok = cvd >= 8 && nor >= 15, floor = cvd >= 6 && nor >= 15;
    if (!floor) bad++;
    out.push(`| ${names[i]} · ${names[j]} | ${cvd.toFixed(1)} | ${nor.toFixed(1)} | ${ok ? 'distinct' : floor ? 'floor band' : '**weak**'} | meter ${4 + i} vs ${4 + j} bars, word |`);
    console.log(`${theme}: ${names[i]} · ${names[j]}: CVD ${cvd.toFixed(1)}, normal ${nor.toFixed(1)}`);
  }
  out.push('');
}
out.push(bad ? `**${bad} problems.**` : 'All bands are distinct to colour-blind and normal vision, at least 3:1 on the surface, with their words at least 4.5:1.', '');
fs.writeFileSync(path.join(here, '..', 'scannable', 'RISK-CVD.md'), out.join('\n'));
console.log(bad ? `${bad} problems` : 'risk bands: distinct, ≥ 3:1, words ≥ 4.5:1');
process.exit(bad ? 1 : 0);
