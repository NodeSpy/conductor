// Bundles icons/lucide/*.svg (ISC, see icons/lucide/LICENSE) and icons/status/*.svg (ours)
// into icons/icons.js for the brand book. Run after adding or changing an icon.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'icons');
const inner = (s) => s.replace(/<!--[\s\S]*?-->/g, '').match(/<svg[^>]*>([\s\S]*)<\/svg>/)[1].replace(/\s+/g, ' ').trim();
const read = (sub) => Object.fromEntries(fs.readdirSync(path.join(dir, sub)).filter((f) => f.endsWith('.svg')).sort()
  .map((f) => [f.slice(0, -4), inner(fs.readFileSync(path.join(dir, sub, f), 'utf8'))]));
// Status glyph meanings, shown in the book next to each glyph.
const LABELS = {
  success: 'Passed, done, healthy (quiet green)', warning: 'Waiting, at risk, degraded', danger: 'Failed, refused', info: 'News, updates',
  running: 'Running (rotates)', neutral: 'Parked, idle (slate)', skipped: 'Skipped, cancelled', shadow: 'Shadow mode: observes, never acts',
  'needs-you': 'Needs you (accent)',
  staged: 'Staged change, not applied',
};
const status = Object.fromEntries(Object.keys(LABELS).map((k) => [k, { label: LABELS[k], svg: read('status')[k] }]));
fs.writeFileSync(path.join(dir, 'icons.js'),
  `// GENERATED by tools/icons.mjs from icons/lucide/*.svg (ISC) and icons/status/*.svg.\nexport const LUCIDE = ${JSON.stringify(read('lucide'), null, 0)};\nexport const STATUS = ${JSON.stringify(status, null, 0)};\n`);
console.log('icons.js:', Object.keys(read('lucide')).length, 'lucide,', Object.keys(status).length, 'status');
