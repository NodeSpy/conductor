// Bundles icons/lucide/*.svg (ISC, see icons/lucide/LICENSE) and icons/status/*.svg (ours)
// into icons/icons.js for the brand book. Run after adding or changing an icon.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'icons');
const inner = (s) => s.replace(/<!--[\s\S]*?-->/g, '').match(/<svg[^>]*>([\s\S]*)<\/svg>/)[1].replace(/\s+/g, ' ').trim();
const read = (sub) => Object.fromEntries(fs.readdirSync(path.join(dir, sub)).filter((f) => f.endsWith('.svg')).sort()
  .map((f) => [f.slice(0, -4), inner(fs.readFileSync(path.join(dir, sub, f), 'utf8'))]));
// Service glyphs (Simple Icons, CC0; the marks are their owners' trademarks): { id: { title, svg } }, 24 grid, one filled path.
const services = Object.fromEntries(fs.readdirSync(path.join(dir, 'services')).filter((f) => f.endsWith('.svg')).sort().map((f) => {
  const s = fs.readFileSync(path.join(dir, 'services', f), 'utf8');
  return [f.slice(0, -4), { title: s.match(/<title>([^<]*)<\/title>/)[1], svg: s.match(/<path[^>]*\/>/)[0] }];
}));
// Status glyph meanings, shown in the book next to each glyph.
const LABELS = {
  success: 'Passed, done, healthy (green)', warning: 'Waiting, at risk, degraded', danger: 'Failed, refused', info: 'News, updates',
  running: 'Running (rotates)', neutral: 'Parked, idle (slate)', skipped: 'Skipped, cancelled', shadow: 'Shadow mode: observes, never acts',
  'needs-you': 'Needs you (accent)',
  staged: 'Staged change, not applied',
  draft: 'Draft: being written, not submitted (slate)',
  ready: 'Ready: set to start, not started (slate)',
  'in-progress': 'In progress: started, not executing now (slate)',
};
const status = Object.fromEntries(Object.keys(LABELS).map((k) => [k, { label: LABELS[k], svg: read('status')[k] }]));
fs.writeFileSync(path.join(dir, 'icons.js'),
  `// GENERATED by tools/icons.mjs from icons/lucide/*.svg (ISC), icons/status/*.svg and icons/services/*.svg (Simple Icons, CC0).\nexport const LUCIDE = ${JSON.stringify(read('lucide'), null, 0)};\nexport const STATUS = ${JSON.stringify(status, null, 0)};\nexport const SERVICES = ${JSON.stringify(services, null, 0)};\n`);
console.log('icons.js:', Object.keys(read('lucide')).length, 'lucide,', Object.keys(status).length, 'status');
