// Colour-blind check for the status marks: every pair of state colours, in both themes, against
// bg.surface, with the dataviz skill's validator (Machado 2009 protan/deutan simulation, OKLab ΔE×100).
//
//   DATAVIZ_VALIDATOR=/path/to/validate_palette.js node tools/status-cvd.mjs
//
// Writes tokens/STATUS-CVD.md. Colour alone is not required to separate every pair: each state also
// has its own shape, so a pair below the colour floor is acceptable only if its shapes differ, which
// this script records. It exits 1 if any mark is below 3:1 against the surface, or if two states
// share a shape.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const T = JSON.parse(fs.readFileSync(path.join(here, '..', 'tokens', 'tokens.json'), 'utf8'));
const { validate, contrast } = await import(pathToFileURL(process.env.DATAVIZ_VALIDATOR).href);

const get = (p) => p.split('.').reduce((o, k) => o[k], T);
function hex(p, theme) {
  let t = get(p), v = t.$extensions?.mode?.[theme] ?? t.$value;
  while (typeof v === 'string') { t = get(v.slice(1, -1)); v = t.$extensions?.mode?.[theme] ?? t.$value; }
  return v.hex;
}
// state → [colour token, shape]
const STATES = {
  Passed: ['semantic.color.status.success.solid', 'filled dot'],
  Running: ['semantic.color.status.running.solid', 'open arc'],
  Failed: ['semantic.color.status.danger.solid', 'cross'],
  'Needs you': ['semantic.color.accent.default', 'diamond'],
  Waiting: ['semantic.color.status.warning.solid', 'triangle'],
  Parked: ['semantic.color.status.neutral.solid', 'pause bars'],
  Shadow: ['semantic.color.status.info.solid', 'half disc'],
  'Not reached': ['semantic.color.status.neutral.solid', 'dash'],
};
const names = Object.keys(STATES);
const shapes = names.map((n) => STATES[n][1]);
const dupShapes = shapes.filter((s, i) => shapes.indexOf(s) !== i);
const num = (row) => +(row[2].match(/ΔE ([\d.]+)/)?.[1] ?? 0);

let bad = dupShapes.length;
const out = ['# Status marks: colour-blind check', '',
  'GENERATED by `tools/status-cvd.mjs` with the dataviz skill’s `validate_palette.js` (Machado 2009 protanopia/deuteranopia, OKLab ΔE×100). Every pair of state colours is compared on `bg.surface`. The thresholds are a CVD ΔE target of 8 (floor 6) and a normal-vision floor of 15.', '',
  '“Not reached” deliberately shares parked’s slate (both mean inactive) and differs by shape (dash vs pause bars). Every state also has its own **shape**, so a pair that colour alone can’t separate is still distinguishable in one colour, for colour-blind readers and in forced-colours mode. ' + (dupShapes.length ? `**Shared shapes: ${dupShapes.join(', ')}**` : 'No two states share a shape.'), ''];
for (const theme of ['light', 'dark']) {
  const surface = hex('semantic.color.bg.surface', theme);
  const cols = names.map((n) => hex(STATES[n][0], theme));
  out.push(`## ${theme} (surface ${surface})`, '', '| State | Colour | Shape | Mark vs surface |', '|---|---|---|---|');
  names.forEach((n, i) => { const c = contrast(cols[i], surface); if (c < 3) bad++; out.push(`| ${n} | \`${cols[i]}\` | ${STATES[n][1]} | ${c.toFixed(2)}${c < 3 ? ' **below 3**' : ''} |`); });
  out.push('', '| Pair | CVD ΔE (worst of protan/deutan) | Normal ΔE | By colour | By shape |', '|---|---|---|---|---|');
  let weak = 0;
  for (let i = 0; i < names.length; i++) for (let j = i + 1; j < names.length; j++) {
    const { report } = validate([cols[i], cols[j]], { mode: theme, surface });
    const cvd = num(report.find((r) => r[0] === 'CVD separation')), nor = num(report.find((r) => r[0] === 'Normal-vision floor'));
    const ok = cvd >= 8 && nor >= 15, floor = cvd >= 6 && nor >= 15;
    if (!ok) weak++;
    out.push(`| ${names[i]} · ${names[j]} | ${cvd.toFixed(1)} | ${nor.toFixed(1)} | ${ok ? 'distinct' : floor ? 'floor band' : '**weak**'} | ${STATES[names[i]][1]} vs ${STATES[names[j]][1]} |`);
  }
  out.push('', `${weak} of ${(names.length * (names.length - 1)) / 2} pairs rely on shape as well as colour in ${theme}.`, '');
  console.log(`${theme}: ${weak} pairs rely on shape`);
}
fs.writeFileSync(path.join(here, '..', 'tokens', 'STATUS-CVD.md'), out.join('\n') + '\n');
console.log(bad ? `${bad} problems (marks below 3:1 or shared shapes)` : 'all marks ≥ 3:1, all shapes distinct');
process.exit(bad ? 1 : 0);
